/**
 * Документ по адресу страницы. Работает и с /terms, и с /terms.html, и с
 * подпапкой хостинга вида /app-landing/terms: смотрим только последний сегмент.
 */
export function docForPath(pathname) {
  const last = String(pathname ?? '')
    .replace(/\/+$/, '')
    .split('/')
    .pop()
    .replace(/\.html$/, '');
  return DOCS[last] ?? null;
}
