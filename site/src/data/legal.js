/**
 * Документ по адресу страницы: /faq/docs/terms, /faq/docs/terms.html и
 * подпапка хостинга вида /app-landing/faq/docs/terms. Всё, что не лежит под
 * faq/docs, документом не считается — на корневые адреса документы больше не
 * отвечают.
 */
export function docForPath(pathname) {
  const match = String(pathname ?? '').match(
    new RegExp(`(?:^|/)${DOCS_DIR}/([^/]+?)(?:\\.html)?/?$`),
  );
  return (match && DOCS[match[1]]) ?? null;
}
